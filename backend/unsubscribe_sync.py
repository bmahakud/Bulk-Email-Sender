"""
Unified Unsubscribe Sync Engine
Synchronizes unsubscribed recipients from BOTH:
  1. Cloud Unsubscribe Server (https://promailer-licensing.diracai.com) — #UNSUBSCRIBE# links & RFC 8058 HTTPS POST
  2. Active Outlook/Exchange Sender Inboxes (Inbox & Junk Email) — Header List-Unsubscribe mailto: clicks (e.g. Gmail/Apple/Outlook header button)
"""
import os
import re
import time
import threading
import urllib.parse
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timedelta, timezone
from typing import Dict, List, Optional, Tuple

import msal
import requests

CLOUD_UNSUB_LIST_URL = "https://promailer-licensing.diracai.com/api/unsubscribed"
CLOUD_UNSUB_PUSH_URL = "https://promailer-licensing.diracai.com/unsubscribe"

_sync_lock = threading.Lock()
_last_inbox_sync_ts: float = 0.0
_INBOX_COOLDOWN_SEC: float = 20.0

_EMAIL_RE = re.compile(r"[\w\.\+\-]+@[\w\.\-]+\.[a-zA-Z]{2,}")
_UNSUB_SUBJ_RE = re.compile(
    r"^\s*(?:re:\s*|fwd:\s*)?(?:auto-)?(?:list-)?unsubscribe\b",
    re.IGNORECASE,
)
_IGNORE_FROM_KEYWORDS = (
    "mailer-daemon",
    "postmaster",
    "noreply",
    "no-reply",
    "do-not-reply",
    "donotreply",
    "microsoftexchange",
    "account-security-noreply",
    "member_services@outlook.com",
    "protection.outlook.com",
)
_IGNORE_TARGET_EMAILS = (
    "unsubscribe@diracai.com",
)
_IGNORE_SUBJ_PREFIXES = (
    "undeliverable",
    "delivery status notification",
    "returned mail",
    "failure notice",
    "mail delivery failed",
)


def _get_license_identifiers(db) -> Tuple[str, str]:
    """Extract (license_key, customer_name) from local settings DB."""
    lic_key = ""
    cust_name = ""
    try:
        token = db.get_setting("license_token", default="")
        if token:
            from backend.license_validator import verify_token

            payload = verify_token(token)
            lic_key = (payload.get("license_key") or "").strip()
            cust_name = (payload.get("customer_name") or "").strip()
    except Exception:
        pass
    return lic_key, cust_name


def _parse_iso_utc(dt_str: str) -> Tuple[Optional[datetime], Optional[str]]:
    """Parse Graph ISO 8601 UTC timestamp to (datetime, 'YYYY-MM-DD HH:MM:SS')."""
    if not dt_str:
        return None, None
    try:
        clean = dt_str.strip()
        if clean.endswith("Z"):
            clean = clean[:-1] + "+00:00"
        dt = datetime.fromisoformat(clean)
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        dt_utc = dt.astimezone(timezone.utc)
        return dt_utc, dt_utc.strftime("%Y-%m-%d %H:%M:%S")
    except Exception:
        return None, None


def _extract_unsubscribe_from_message(msg: Dict, sender_email: str) -> Optional[Dict]:
    """
    Validate whether a Graph message is a recipient unsubscribe request (e.g. from List-Unsubscribe mailto).
    Returns dict {msg_id, sender_email, unsub_email, received_utc, received_dt} or None.
    """
    if not msg or msg.get("isDraft"):
        return None
    msg_id = (msg.get("id") or "").strip()
    if not msg_id:
        return None

    subj_raw = (msg.get("subject") or "").strip()
    subj_low = subj_raw.lower()
    from_addr = (
        ((msg.get("from") or {}).get("emailAddress") or {}).get("address") or ""
    ).strip().lower()
    body_prev = (msg.get("bodyPreview") or "").strip().lower()
    recv_raw = (msg.get("receivedDateTime") or "").strip()

    sender_low = (sender_email or "").strip().lower()
    if from_addr and from_addr == sender_low:
        return None
    if any(k in from_addr for k in _IGNORE_FROM_KEYWORDS):
        return None
    if any(subj_low.startswith(p) for p in _IGNORE_SUBJ_PREFIXES):
        return None

    is_unsub_intent = bool(_UNSUB_SUBJ_RE.match(subj_raw)) or (
        "automatically generated by gmail" in body_prev and "unsubscribe" in subj_low
    ) or (subj_low in ("unsubscribe", "unsubscribe request", "opt out", "opt-out"))

    if not is_unsub_intent:
        return None

    # Extract email from URL-decoded subject first, then fallback to sender of the unsubscribe message
    subj_decoded = urllib.parse.unquote(subj_raw)
    unsub_email = ""
    for m in _EMAIL_RE.finditer(subj_decoded):
        cand = m.group(0).strip().lower()
        if (
            cand != sender_low
            and cand not in _IGNORE_TARGET_EMAILS
            and not any(k in cand for k in _IGNORE_FROM_KEYWORDS)
        ):
            unsub_email = cand
            break

    if not unsub_email and from_addr:
        m_from = _EMAIL_RE.fullmatch(from_addr)
        if m_from and from_addr != sender_low and from_addr not in _IGNORE_TARGET_EMAILS:
            unsub_email = from_addr

    if not unsub_email or "@" not in unsub_email or "." not in unsub_email:
        return None

    dt_utc, utc_str = _parse_iso_utc(recv_raw)
    if dt_utc:
        # Skip extremely stale (> 30 days old) inbox artifacts
        if datetime.now(timezone.utc) - dt_utc > timedelta(days=30):
            return None

    return {
        "msg_id": msg_id,
        "sender_email": sender_low,
        "unsub_email": unsub_email,
        "received_utc": utc_str,
        "received_dt": dt_utc or datetime.min.replace(tzinfo=timezone.utc),
    }


def _poll_single_account_inbox(account: Dict, timeout: int = 6) -> Tuple[List[Dict], Optional[str], Optional[str]]:
    """
    Poll one Outlook/Exchange account's Inbox and Junk Email via Microsoft Graph API.
    Strictly read-only; never modifies SMTP status or triggers errors on Mail.Send-only accounts.
    Returns (matched_messages, sender_email, optional_new_refresh_token).
    """
    sender_email = (account.get("email") or "").strip()
    token_val = (account.get("token") or "").strip()
    client_id = (account.get("client_id") or "").strip()
    if not sender_email or not token_val or not client_id:
        return [], sender_email, None

    is_uuid_tenant = bool(
        re.match(
            r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$",
            token_val,
        )
    )
    is_hve = is_uuid_tenant or token_val.lower().startswith("hve:")

    access_token = None
    new_refresh = None

    try:
        if is_hve:
            from backend.hve_sender import HVESender

            tenant_id = token_val.replace("hve:", "").strip()
            secret = account.get("password", "")
            access_token = HVESender.get_access_token(
                tenant_id=tenant_id,
                client_id=client_id,
                client_secret=secret,
                scope="https://graph.microsoft.com/.default",
            )
            base_folder_url = f"https://graph.microsoft.com/v1.0/users/{urllib.parse.quote(sender_email)}/mailFolders"
        else:
            app = msal.PublicClientApplication(
                client_id=client_id,
                authority="https://login.microsoftonline.com/common",
            )
            res = app.acquire_token_by_refresh_token(
                refresh_token=token_val,
                scopes=["https://graph.microsoft.com/.default"],
            )
            if "access_token" not in res:
                res = app.acquire_token_by_refresh_token(
                    refresh_token=token_val,
                    scopes=["Mail.Read"],
                )
            if "access_token" not in res:
                env_tenant = (os.getenv("TENANT_ID") or "").strip()
                if env_tenant and env_tenant.lower() != "common":
                    tenant_app = msal.PublicClientApplication(
                        client_id=client_id,
                        authority=f"https://login.microsoftonline.com/{env_tenant}",
                    )
                    res = tenant_app.acquire_token_by_refresh_token(
                        refresh_token=token_val,
                        scopes=["https://graph.microsoft.com/.default"],
                    )
            if "access_token" in res:
                access_token = res["access_token"]
                rf = res.get("refresh_token")
                if rf and rf != token_val:
                    new_refresh = rf
            base_folder_url = "https://graph.microsoft.com/v1.0/me/mailFolders"
    except Exception:
        return [], sender_email, None

    if not access_token:
        return [], sender_email, None

    matches: List[Dict] = []
    sess = requests.Session()
    headers = {"Authorization": f"Bearer {access_token}"}

    folders = [
        ("inbox", 25),
        ("junkemail", 15),
    ]
    try:
        for folder_name, top_n in folders:
            url = (
                f"{base_folder_url}/{folder_name}/messages"
                f"?%24top={top_n}&%24orderby=receivedDateTime%20desc"
                f"&%24select=id,subject,from,receivedDateTime,bodyPreview,isDraft"
            )
            try:
                resp = sess.get(url, headers=headers, timeout=timeout)
                if resp.status_code != 200:
                    continue
                for msg in resp.json().get("value", []):
                    parsed = _extract_unsubscribe_from_message(msg, sender_email)
                    if parsed:
                        matches.append(parsed)
            except Exception:
                continue
    finally:
        sess.close()

    return matches, sender_email, new_refresh


def sync_all_unsubscribes(
    db,
    force_inbox: bool = False,
    max_accounts: int = 15,
    include_inbox: bool = True,
    request_timeout: int = 10,
) -> Dict:
    """
    Synchronize unsubscribed contacts from BOTH Cloud Server and Sender Outlook Inboxes.

    Returns dict:
      {
        "total_server": int,
        "added_count": int,
        "inbox_added": int,
        "cloud_added": int,
        "server_reachable": bool,
        "skipped_busy": bool,
      }
    """
    global _last_inbox_sync_ts

    acquired = _sync_lock.acquire(blocking=force_inbox, timeout=12 if force_inbox else 0)
    if not acquired:
        return {
            "total_server": 0,
            "added_count": 0,
            "inbox_added": 0,
            "cloud_added": 0,
            "server_reachable": True,
            "skipped_busy": True,
        }

    try:
        lic_key, cust_name = _get_license_identifiers(db)
        active_lic = cust_name or lic_key or "Pooja"

        candidate_params = []
        if lic_key:
            candidate_params.append({"lic": lic_key})
        if cust_name and cust_name != lic_key:
            candidate_params.append({"lic": cust_name})
        candidate_params.append({})

        all_server_records: Dict[str, Dict] = {}
        server_reachable = False
        cloud_added = 0
        inbox_added = 0

        sess = requests.Session()
        try:
            # 1. Fetch Cloud Server Unsubscribed Contacts (#UNSUBSCRIBE# & HTTPS One-Click)
            for p in candidate_params:
                try:
                    resp = sess.get(CLOUD_UNSUB_LIST_URL, params=p, timeout=request_timeout)
                    if resp.status_code == 200:
                        server_reachable = True
                        for item in resp.json().get("emails", []):
                            em = (item.get("email") or "").strip().lower()
                            if not em:
                                continue
                            new_ts = db._normalize_utc_ts(item.get("unsubscribed_at"))
                            prev_item = all_server_records.get(em)
                            if prev_item is None:
                                all_server_records[em] = item
                            else:
                                prev_ts = db._normalize_utc_ts(prev_item.get("unsubscribed_at"))
                                if new_ts > prev_ts:
                                    all_server_records[em] = item
                except requests.exceptions.RequestException:
                    break
                except Exception:
                    continue

            for em, item in all_server_records.items():
                unsub_at = item.get("unsubscribed_at")
                if db.add_unsubscribed(em, unsubscribed_at=unsub_at, respect_removal=True):
                    cloud_added += 1

            # 2. Poll Sender Inboxes for List-Unsubscribe mailto: messages (e.g. Gmail Header Unsubscribe)
            now_ts = time.time()
            should_poll_inbox = include_inbox and (
                force_inbox or (now_ts - _last_inbox_sync_ts >= _INBOX_COOLDOWN_SEC)
            )
            if should_poll_inbox:
                _last_inbox_sync_ts = now_ts
                accounts = db.get_active_smtp_for_unsub_sync(limit=max_accounts)
                if accounts:
                    collected: List[Dict] = []
                    refreshed_tokens: List[Tuple[str, str]] = []
                    workers = min(5, len(accounts))
                    inbox_timeout = min(6, request_timeout)

                    with ThreadPoolExecutor(max_workers=workers) as pool:
                        futures = [
                            pool.submit(_poll_single_account_inbox, acc, inbox_timeout)
                            for acc in accounts
                        ]
                        for fut in as_completed(futures):
                            try:
                                items, s_email, new_rf = fut.result()
                                if items:
                                    collected.extend(items)
                                if new_rf and s_email:
                                    refreshed_tokens.append((s_email, new_rf))
                            except Exception:
                                continue

                    # Persist any rotated refresh tokens
                    for s_email, new_rf in refreshed_tokens:
                        try:
                            db.update_smtp_token(s_email, new_rf)
                        except Exception:
                            pass

                    # Sort newest-first so most recent unsubscribe timestamp is recorded first
                    collected.sort(key=lambda x: x["received_dt"], reverse=True)

                    for item in collected:
                        msg_id = item["msg_id"]
                        if db.is_unsub_message_processed(msg_id):
                            continue

                        unsub_em = item["unsub_email"]
                        s_email = item["sender_email"]
                        utc_str = item["received_utc"]

                        # Mark processed first so subsequent user Remove/Clear will not resurrect old mail
                        db.mark_unsub_message_processed(msg_id, s_email, unsub_em)

                        if db.add_unsubscribed(unsub_em, unsubscribed_at=utc_str, respect_removal=True):
                            inbox_added += 1
                            # Also push to Cloud Server so all machines / admin panel stay synchronized
                            if unsub_em not in all_server_records:
                                try:
                                    push_resp = sess.get(
                                        CLOUD_UNSUB_PUSH_URL,
                                        params={"lic": active_lic, "email": unsub_em},
                                        timeout=request_timeout,
                                    )
                                    if push_resp.status_code in (200, 201, 204):
                                        server_reachable = True
                                        all_server_records[unsub_em] = {
                                            "email": unsub_em,
                                            "unsubscribed_at": utc_str or "",
                                        }
                                except Exception:
                                    pass
        finally:
            sess.close()

        return {
            "total_server": len(all_server_records),
            "added_count": cloud_added + inbox_added,
            "inbox_added": inbox_added,
            "cloud_added": cloud_added,
            "server_reachable": server_reachable,
            "skipped_busy": False,
        }
    finally:
        _sync_lock.release()
